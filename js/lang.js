// Current language
App._lang = localStorage.getItem('actas_lang') || 'es';

App._t = function (key) {
    const keys = key.split('.');
    let val = LANG[App._lang];
    for (const k of keys) {
        if (!val || typeof val !== 'object') return key;
        val = val[k];
    }
    if (val === undefined || val === null) return key;
    // Replace {0}, {1}, ... with extra args
    const args = Array.prototype.slice.call(arguments, 1);
    if (args.length) {
        return val.replace(/\{(\d+)\}/g, function (m, i) {
            return args[parseInt(i)] !== undefined ? args[parseInt(i)] : m;
        });
    }
    return val;
};

App.setLang = function (lang) {
    if (!LANG[lang]) return;
    App._lang = lang;
    localStorage.setItem('actas_lang', lang);
    App.applyStaticLang();
    document.getElementById('app-title').textContent = App._t('appName');
    if (App.currentPage) {
        App.navTo(App.currentPage);
    }
    const langName = lang === 'eu' ? 'Euskera' : 'Espa\u00f1ol';
    App.toast(App._t('settings.langChanged', langName), 'info');
};
